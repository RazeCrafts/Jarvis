/**
 * Bundles src/workspace/runtime.ts into a single IIFE that is inlined into the
 * artifact iframe. Three.js + OrbitControls + GLTFExporter ship locally, so
 * artifacts render with no network at all.
 *
 * Run automatically by `npm run dev` / `npm run build`.
 */

import { build } from "esbuild";
import { writeFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const entry = resolve(root, "src/workspace/runtime.ts");
const outfile = resolve(root, "src/workspace/runtime.generated.js");

const result = await build({
  entryPoints: [entry],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: ["es2020"],
  minify: true,
  legalComments: "none",
  write: false,
  logLevel: "warning",
});

const output = result.outputFiles?.[0]?.text;
if (!output) throw new Error("esbuild produced no output");

await mkdir(dirname(outfile), { recursive: true });
await writeFile(
  outfile,
  `/* Generated by tools/build-workspace-runtime.mjs — do not edit. */\n${output}\n`,
  "utf8",
);

console.log(`workspace runtime: ${(output.length / 1024).toFixed(1)} KB -> ${outfile}`);
