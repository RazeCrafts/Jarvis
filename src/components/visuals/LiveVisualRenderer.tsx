import { useMemo, useRef, useState } from "react";
import { Download, Expand } from "lucide-react";
import type { LiveVisualSpec } from "@/types";
import { useUiStore, useWorkspaceStore } from "@/store";

const SERIES_COLORS = [
  "var(--color-accent)",
  "#f59e0b",
  "#10b981",
  "#f43f5e",
  "#8b5cf6",
];

function buildStandaloneHtml(spec: LiveVisualSpec): string {
  const json = JSON.stringify(spec).replace(/</g, "\\u003c");
  return `<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<title>${spec.title}</title>
<style>
  body { margin: 0; font-family: system-ui, sans-serif; background: #080c14; color: #eef4ff; padding: 28px; }
  h1 { margin: 0 0 6px; font-size: 20px; }
  p { margin: 0 0 18px; color: #8ba0be; font-size: 13px; }
  table { width: 100%; border-collapse: collapse; margin-top: 12px; }
  th, td { border: 1px solid #22314a; padding: 8px 12px; text-align: left; font-size: 13px; }
  th { background: #141e30; color: #22d3ee; }
</style>
</head>
<body>
  <h1>${spec.title}</h1>
  <p>${spec.subtitle || "Live Visual Artifact generated by JARVIS"}</p>
  <div id="mount"></div>
  <script>
    const spec = ${json};
    const mount = document.getElementById("mount");
    if (spec.nodes && spec.nodes.length) {
      mount.innerHTML = spec.nodes.map((n, i) => '<div style="border:1px solid #22314a;padding:10px 14px;border-radius:10px;margin-bottom:8px;background:#0e1523"><strong>' + (i+1) + '. ' + n.label + '</strong>' + (n.detail ? '<div style="color:#8ba0be;font-size:12px;margin-top:4px">' + n.detail + '</div>' : '') + '</div>').join("");
    } else if (spec.labels && spec.series) {
      let html = '<table><thead><tr><th>Category</th>' + spec.series.map(s => '<th>' + s.name + '</th>').join('') + '</tr></thead><tbody>';
      spec.labels.forEach((lbl, idx) => {
        html += '<tr><td>' + lbl + '</td>' + spec.series.map(s => '<td>' + (s.values[idx] ?? '-') + '</td>').join('') + '</tr>';
      });
      html += '</tbody></table>';
      mount.innerHTML = html;
    }
  </script>
</body>
</html>`;
}

export function LiveVisualRenderer({ visual }: { visual: LiveVisualSpec }) {
  const svgRef = useRef<SVGSVGElement>(null);
  const [hoverInfo, setHoverInfo] = useState<string | null>(null);
  const upsertArtifact = useWorkspaceStore((s) => s.upsertArtifact);
  const setActiveTab = useUiStore((s) => s.setActiveTab);

  const labels = useMemo(() => visual.labels || [], [visual.labels]);
  const series = useMemo(() => visual.series || [], [visual.series]);
  const nodes = useMemo(() => visual.nodes || [], [visual.nodes]);
  const edges = useMemo(() => visual.edges || [], [visual.edges]);

  const maxVal = useMemo(() => {
    let max = 1;
    for (const s of series) {
      for (const v of s.values || []) {
        if (Math.abs(v) > max) max = Math.abs(v);
      }
    }
    return max * 1.12;
  }, [series]);

  const downloadSvg = () => {
    if (!svgRef.current) return;
    const xml = new XMLSerializer().serializeToString(svgRef.current);
    const blob = new Blob([xml], { type: "image/svg+xml;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = `${visual.title.toLowerCase().replace(/[^a-z0-9]+/g, "-") || "chart"}.svg`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const expandToWorkshop = () => {
    upsertArtifact({
      id: `vis-${visual.id}`,
      kind: "html",
      title: visual.title,
      language: "html",
      content: buildStandaloneHtml(visual),
      version: 1,
      versions: [1],
      createdAt: Date.now(),
      updatedAt: Date.now(),
      remote: false,
    });
    setActiveTab("workspace");
  };

  const W = 520;
  const H = 220;
  const PAD_L = 42;
  const PAD_R = 16;
  const PAD_T = 18;
  const PAD_B = 34;
  const plotW = W - PAD_L - PAD_R;
  const plotH = H - PAD_T - PAD_B;

  return (
    <div className="hud-elevated mt-3 overflow-hidden p-3.5">
      <div className="mb-2 flex items-start justify-between gap-3">
        <div>
          <h4 className="text-xs font-semibold tracking-tight text-fg">{visual.title}</h4>
          {visual.subtitle && <p className="text-[11px] text-fg-muted">{visual.subtitle}</p>}
        </div>
        <div className="flex items-center gap-1">
          {visual.chartType !== "table" && (
            <button
              type="button"
              onClick={downloadSvg}
              title="Download SVG"
              className="rounded-md p-1.5 text-fg-muted transition-colors hover:bg-surface hover:text-fg"
            >
              <Download size={13} />
            </button>
          )}
          <button
            type="button"
            onClick={expandToWorkshop}
            title="Expand to Workshop"
            className="flex items-center gap-1 rounded-md px-2 py-1 text-[11px] font-medium text-accent transition-colors hover:bg-surface"
          >
            <Expand size={12} /> Workshop
          </button>
        </div>
      </div>

      {hoverInfo && (
        <div className="mb-1.5 font-mono text-[11px] text-accent tabular-nums">{hoverInfo}</div>
      )}

      {visual.chartType === "table" && (
        <div className="overflow-x-auto">
          <table className="w-full border-collapse text-left text-xs">
            <thead>
              <tr className="border-b border-border text-fg-muted">
                <th className="py-1.5 pr-3 font-medium">Item</th>
                {series.map((s) => (
                  <th key={s.name} className="px-2 py-1.5 font-medium">
                    {s.name}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody>
              {labels.map((lbl, idx) => (
                <tr key={lbl + idx} className="border-b border-border/50">
                  <td className="py-1.5 pr-3 text-fg">{lbl}</td>
                  {series.map((s) => (
                    <td key={s.name} className="px-2 py-1.5 font-mono tabular-nums text-fg">
                      {s.values[idx] ?? "—"}
                    </td>
                  ))}
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}

      {visual.chartType === "flowchart" && (
        <div className="space-y-2">
          <svg ref={svgRef} viewBox={`0 0 ${W} ${Math.max(120, nodes.length * 56)}`} className="w-full">
            {nodes.map((node, i) => {
              const y = 16 + i * 54;
              return (
                <g
                  key={node.id}
                  onMouseEnter={() => setHoverInfo(node.detail || node.label)}
                  onMouseLeave={() => setHoverInfo(null)}
                  className="cursor-pointer"
                >
                  <rect
                    x={20}
                    y={y}
                    width={W - 40}
                    height={40}
                    rx={8}
                    fill="var(--color-surface)"
                    stroke="var(--color-border)"
                    strokeWidth={1.2}
                  />
                  <circle cx={38} cy={y + 20} r={5} fill="var(--color-accent)" />
                  <text x={52} y={y + 18} fill="var(--color-fg)" fontSize="12" fontWeight="600">
                    {node.label}
                  </text>
                  {node.detail && (
                    <text x={52} y={y + 32} fill="var(--color-fg-muted)" fontSize="10">
                      {node.detail.slice(0, 72)}
                    </text>
                  )}
                  {i < nodes.length - 1 && (
                    <line
                      x1={38}
                      y1={y + 40}
                      x2={38}
                      y2={y + 54}
                      stroke="var(--color-accent)"
                      strokeWidth={1.4}
                    />
                  )}
                </g>
              );
            })}
            {edges.length > 0 && (
              <text x={20} y={Math.max(120, nodes.length * 56) - 4} fill="var(--color-fg-muted)" fontSize="9">
                {edges.length} directed transitions mapped
              </text>
            )}
          </svg>
        </div>
      )}

      {(visual.chartType === "bar" || visual.chartType === "line" || visual.chartType === "area") && (
        <svg ref={svgRef} viewBox={`0 0 ${W} ${H}`} className="w-full overflow-visible">
          {[0, 0.25, 0.5, 0.75, 1].map((t) => {
            const y = PAD_T + plotH * (1 - t);
            return (
              <g key={t}>
                <line x1={PAD_L} y1={y} x2={W - PAD_R} y2={y} stroke="var(--color-border)" strokeDasharray="3 3" />
                <text x={PAD_L - 6} y={y + 3} textAnchor="end" fill="var(--color-fg-muted)" fontSize="9">
                  {Math.round(maxVal * t)}
                </text>
              </g>
            );
          })}

          {labels.map((lbl, idx) => {
            const x = PAD_L + (idx + 0.5) * (plotW / Math.max(1, labels.length));
            return (
              <text key={lbl + idx} x={x} y={H - 10} textAnchor="middle" fill="var(--color-fg-muted)" fontSize="9.5">
                {lbl.slice(0, 10)}
              </text>
            );
          })}

          {visual.chartType === "bar" &&
            series.map((s, sIdx) => {
              const color = SERIES_COLORS[sIdx % SERIES_COLORS.length];
              const groupW = plotW / Math.max(1, labels.length);
              const barW = Math.max(8, (groupW * 0.72) / Math.max(1, series.length));
              return (s.values || []).map((val, idx) => {
                const bh = (Math.max(0, val) / maxVal) * plotH;
                const bx = PAD_L + idx * groupW + groupW * 0.14 + sIdx * barW;
                const by = PAD_T + plotH - bh;
                return (
                  <rect
                    key={`${s.name}-${idx}`}
                    x={bx}
                    y={by}
                    width={barW - 2}
                    height={bh}
                    rx={3}
                    fill={color}
                    opacity={0.88}
                    onMouseEnter={() => setHoverInfo(`${s.name} · ${labels[idx] || idx}: ${val}`)}
                    onMouseLeave={() => setHoverInfo(null)}
                  />
                );
              });
            })}

          {(visual.chartType === "line" || visual.chartType === "area") &&
            series.map((s, sIdx) => {
              const color = SERIES_COLORS[sIdx % SERIES_COLORS.length];
              const pts = (s.values || []).map((val, idx) => {
                const x =
                  labels.length <= 1
                    ? PAD_L + plotW / 2
                    : PAD_L + (idx / (labels.length - 1)) * plotW;
                const y = PAD_T + plotH - (Math.max(0, val) / maxVal) * plotH;
                return { x, y, val };
              });
              const pathD = pts.map((p, i) => `${i === 0 ? "M" : "L"}${p.x.toFixed(1)},${p.y.toFixed(1)}`).join(" ");
              const areaD =
                pts.length > 0
                  ? `${pathD} L${pts[pts.length - 1].x.toFixed(1)},${PAD_T + plotH} L${pts[0].x.toFixed(1)},${PAD_T + plotH} Z`
                  : "";
              return (
                <g key={s.name}>
                  {visual.chartType === "area" && areaD && (
                    <path d={areaD} fill={color} opacity={0.14} />
                  )}
                  {pathD && <path d={pathD} fill="none" stroke={color} strokeWidth={2.2} strokeLinejoin="round" />}
                  {pts.map((p, idx) => (
                    <circle
                      key={idx}
                      cx={p.x}
                      cy={p.y}
                      r={4}
                      fill={color}
                      onMouseEnter={() => setHoverInfo(`${s.name} · ${labels[idx] || idx}: ${p.val}`)}
                      onMouseLeave={() => setHoverInfo(null)}
                    />
                  ))}
                </g>
              );
            })}
        </svg>
      )}

      {(visual.chartType === "pie" || visual.chartType === "radar") && series[0] && (
        <svg ref={svgRef} viewBox={`0 0 ${W} 190`} className="w-full">
          {(() => {
            const vals = series[0].values || [];
            const total = vals.reduce((acc, v) => acc + Math.max(0, v), 0) || 1;
            let angle = -Math.PI / 2;
            const cx = 120;
            const cy = 95;
            const r = 68;
            return (
              <>
                {vals.map((val, idx) => {
                  const slice = (Math.max(0, val) / total) * Math.PI * 2;
                  const x1 = cx + r * Math.cos(angle);
                  const y1 = cy + r * Math.sin(angle);
                  const x2 = cx + r * Math.cos(angle + slice);
                  const y2 = cy + r * Math.sin(angle + slice);
                  const large = slice > Math.PI ? 1 : 0;
                  const d = `M ${cx} ${cy} L ${x1} ${y1} A ${r} ${r} 0 ${large} 1 ${x2} ${y2} Z`;
                  angle += slice;
                  const color = SERIES_COLORS[idx % SERIES_COLORS.length];
                  return (
                    <g key={idx}>
                      <path
                        d={d}
                        fill={color}
                        opacity={0.9}
                        onMouseEnter={() =>
                          setHoverInfo(`${labels[idx] || `Slice ${idx + 1}`}: ${val} (${Math.round((val / total) * 100)}%)`)
                        }
                        onMouseLeave={() => setHoverInfo(null)}
                      />
                      <rect x={230} y={24 + idx * 22} width={10} height={10} rx={2} fill={color} />
                      <text x={248} y={33 + idx * 22} fill="var(--color-fg)" fontSize="11">
                        {labels[idx] || `Item ${idx + 1}`}: {val}
                      </text>
                    </g>
                  );
                })}
              </>
            );
          })()}
        </svg>
      )}

      {series.length > 1 && (
        <div className="mt-2 flex flex-wrap gap-3 text-[11px] text-fg-muted">
          {series.map((s, idx) => (
            <span key={s.name} className="inline-flex items-center gap-1.5">
              <span className="h-2 w-2 rounded-full" style={{ background: SERIES_COLORS[idx % SERIES_COLORS.length] }} />
              {s.name}
            </span>
          ))}
        </div>
      )}
    </div>
  );
}
