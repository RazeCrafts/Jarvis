export function applyThemeToDocument(
  theme: JarvisTheme,
  overrides?: { customAccent?: string; borderRadius?: number },
): void {
  if (typeof document === "undefined") return;
  const root = document.documentElement;
  const accent = overrides?.customAccent?.trim() || theme.accent;
  root.classList.toggle("dark", theme.isDark);
  root.style.colorScheme = theme.isDark ? "dark" : "light";
  root.style.background = theme.background;
  root.style.setProperty("--color-background", theme.background);
  root.style.setProperty("--color-surface", theme.surface);
  root.style.setProperty("--color-elevated", theme.elevated);
  root.style.setProperty("--color-border", theme.border);
  root.style.setProperty("--color-accent", accent);
  root.style.setProperty("--color-accent-soft", theme.accentSoft);
  root.style.setProperty("--color-accent-glow", theme.accentGlow);
  root.style.setProperty("--color-fg", theme.fg);
  root.style.setProperty("--color-fg-muted", theme.fgMuted);
  if (typeof overrides?.borderRadius === "number") {
    root.style.setProperty("--jarvis-radius", `${overrides.borderRadius}px`);
  }
}
